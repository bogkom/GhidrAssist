package ghidrassist.hardware;

import java.util.ArrayList;
import java.util.Collection;
import java.util.Comparator;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * Conservative, non-mutating FUNCTION naming candidates from direct hardware
 * write sites. No processor auto-identification, cross-procedural assumption,
 * function rename API or claimed reset-to-application reachability.
 */
public final class HardwareFunctionNamingReview {
    private HardwareFunctionNamingReview() {}

    public record Observation(long functionAddress, String functionName,
            long instructionAddress, String registerName, boolean write) {}

    public static final class Proposal {
        public final long functionAddress;
        public final String currentName, proposedName, role, registers;
        public final int writeSites;
        public final HardwareNamingReview.Status status;
        private Proposal(long address,String current,String proposed,String role,
                String registers,int writes,HardwareNamingReview.Status status) {
            functionAddress=address;currentName=current;proposedName=proposed;
            this.role=role;this.registers=registers;writeSites=writes;this.status=status;
        }

        private static String cell(String v) {
            return "\"" + (v==null?"":v).replace("\"","\"\"")
                .replace("\r"," ").replace("\n"," ") + "\"";
        }
        /** Compatible with the existing seven-column register-review CSV. */
        public String csv() {
            return cell(ChipSelectModel.hex(functionAddress,6))+","+
                cell(currentName)+","+cell(proposedName)+","+
                cell("MC68332 HYPOTHESIS")+","+
                cell("FUNCTION_ROLE:"+role+"; writes="+registers)+","+
                writeSites+","+cell(status.name())+"\n";
        }
    }

    private static final class Group {
        String name;
        final Set<String> registers=new LinkedHashSet<>();
        final Set<Long> sites=new LinkedHashSet<>();
        Group(String name) {this.name=name;}
    }

    private static boolean hasAny(Set<String> registers,String prefix) {
        for(String name:registers)if(name.startsWith(prefix))return true;
        return false;
    }
    private static String role(Set<String> names) {
        if(hasAny(names,"CSBAR") && hasAny(names,"CSOR") &&
                hasAny(names,"CSPAR")) return "CONFIGURE_CHIP_SELECTS";
        if(names.contains("SIMCR") && names.contains("SYNCR"))
            return "CONFIGURE_SIM_CLOCK";
        if(names.contains("TRAMBAR") && names.contains("TPUMCR"))
            return "CONFIGURE_TPURAM_TPU";
        return "";
    }

    /**
     * Candidate generation requires a manually selected concrete MCU profile,
     * at least three *distinct* write sites, three distinct register names
     * and a narrow role signature; read/XREF-only counts are never sufficient.
     */
    public static List<Proposal> propose(boolean selectedConcrete,
            Collection<Observation> input,Collection<String> existingSymbols) {
        if(input==null || existingSymbols==null)
            throw new IllegalArgumentException("Missing function naming evidence");
        Map<Long,Group> groups=new LinkedHashMap<>();
        for(Observation o:input) {
            if(o==null || o.functionAddress<0 || o.functionAddress>0xffffffL ||
                    o.instructionAddress<0 || o.instructionAddress>0xffffffL ||
                    o.functionName==null || o.registerName==null ||
                    !o.write) continue;
            Group g=groups.computeIfAbsent(o.functionAddress,
                unused->new Group(o.functionName));
            g.name=o.functionName;
            g.sites.add(o.instructionAddress);
            g.registers.add(o.registerName.toUpperCase(Locale.ROOT));
        }
        Set<String> reserved=new HashSet<>();
        for(String name:existingSymbols)
            if(name!=null)reserved.add(name.toUpperCase(Locale.ROOT));
        List<Proposal> out=new ArrayList<>();
        for(var e:groups.entrySet()) {
            long address=e.getKey();
            Group g=e.getValue();
            if(g.sites.size()<2 || g.registers.size()<2)continue;
            String role=role(g.registers);
            boolean autogenerated=g.name.matches("(?i)(?:FUN|SUB)_[0-9A-F]{4,16}");
            String proposed="HW_MC68332_"+role+"_CANDIDATE_"+
                String.format(Locale.ROOT,"%06X",address);
            HardwareNamingReview.Status status;
            if(!selectedConcrete)status=HardwareNamingReview.Status.FAMILY_UNCERTAIN;
            else if(!autogenerated)status=HardwareNamingReview.Status.ALREADY_NAMED;
            else if(role.isEmpty() || g.registers.size()<3 || g.sites.size()<3)
                status=HardwareNamingReview.Status.EVIDENCE_TOO_WEAK;
            else if(reserved.contains(proposed.toUpperCase(Locale.ROOT)))
                status=HardwareNamingReview.Status.NAME_COLLISION;
            else status=HardwareNamingReview.Status.REVIEW_REQUIRED;
            List<String> names=new ArrayList<>(g.registers);
            names.sort(String::compareTo);
            out.add(new Proposal(address,g.name,
                status==HardwareNamingReview.Status.REVIEW_REQUIRED?proposed:"",
                role.isEmpty()?"UNCLASSIFIED":role,String.join("|",names),
                g.sites.size(),status));
        }
        out.sort(Comparator.comparingLong(p->p.functionAddress));
        return List.copyOf(out);
    }

    /** Rows only: append to the existing register preview CSV header. */
    public static String toCsvRows(List<Proposal> proposals) {
        StringBuilder b=new StringBuilder();
        for(Proposal p:proposals)b.append(p.csv());
        return b.toString();
    }
}
